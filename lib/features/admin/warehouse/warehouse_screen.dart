import 'package:flutter/material.dart';
import 'package:ailin_tattileri_app/core/models/ingredient_model.dart';
import 'package:ailin_tattileri_app/core/services/warehouse_service.dart';
import 'package:ailin_tattileri_app/features/admin/warehouse/warehouse_transactions_screen.dart';
import 'package:ailin_tattileri_app/core/theme/app_colors.dart';
import 'package:ailin_tattileri_app/l10n/app_localizations.dart';

class WarehouseScreen extends StatefulWidget {
  const WarehouseScreen({super.key});

  @override
  State<WarehouseScreen> createState() => _WarehouseScreenState();
}

class _WarehouseScreenState extends State<WarehouseScreen>
    with SingleTickerProviderStateMixin {
  final WarehouseService _warehouseService = WarehouseService();
  String _searchQuery = "";
  late TabController _tabController;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 2, vsync: this);
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  // --- METHODS ---

  void _showAddEditIngredientDialog({Ingredient? ingredient}) {
    final nameController = TextEditingController(text: ingredient?.name);
    final unitController = TextEditingController(
      text: ingredient?.unit ?? 'кг',
    );
    final minQtyController = TextEditingController(
      text: ingredient?.minQuantity.toString(),
    );
    bool isLoading = false;

    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (context) => StatefulBuilder(
        builder: (context, setState) {
          return AlertDialog(
            title: Text(
              ingredient == null
                  ? AppLocalizations.of(context)!.addIngredient
                  : AppLocalizations.of(context)!.editIngredient,
            ),
            content: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                TextField(
                  controller: nameController,
                  decoration: InputDecoration(
                    labelText: AppLocalizations.of(context)!.nameLabel,
                  ),
                ),
                TextField(
                  controller: unitController,
                  decoration: InputDecoration(
                    labelText: AppLocalizations.of(context)!.unitLabel,
                  ),
                ),
                TextField(
                  controller: minQtyController,
                  keyboardType: TextInputType.number,
                  decoration: InputDecoration(
                    labelText: AppLocalizations.of(context)!.minStockLabel,
                  ),
                ),
              ],
            ),
            actions: [
              TextButton(
                onPressed: isLoading ? null : () => Navigator.pop(context),
                child: Text(AppLocalizations.of(context)!.cancel),
              ),
              ElevatedButton(
                onPressed: isLoading
                    ? null
                    : () async {
                        if (nameController.text.trim().isEmpty) return;

                        setState(() => isLoading = true);
                        try {
                          final double minQty =
                              double.tryParse(minQtyController.text) ?? 5.0;

                          if (ingredient == null) {
                            final newIngredient = Ingredient(
                              id: '', // Generated by Firestore
                              name: nameController.text.trim(),
                              unit: unitController.text.trim(),
                              minQuantity: minQty,
                              quantity: 0,
                              pricePerUnit: 0,
                              lastUpdated: DateTime.now(),
                            );
                            await _warehouseService.addIngredient(
                              newIngredient,
                            );
                          } else {
                            final updatedIngredient = Ingredient(
                              id: ingredient.id,
                              name: nameController.text.trim(),
                              unit: unitController.text.trim(),
                              minQuantity: minQty,
                              quantity: ingredient.quantity,
                              pricePerUnit: ingredient.pricePerUnit,
                              lastUpdated: DateTime.now(),
                            );
                            await _warehouseService.updateIngredient(
                              updatedIngredient,
                            );
                          }
                          if (context.mounted) Navigator.pop(context);
                        } catch (e) {
                          if (context.mounted) {
                            setState(() => isLoading = false);
                            ScaffoldMessenger.of(context).showSnackBar(
                              SnackBar(content: Text("Ошибка: $e")),
                            );
                          }
                        }
                      },
                child: isLoading
                    ? const SizedBox(
                        width: 20,
                        height: 20,
                        child: CircularProgressIndicator(strokeWidth: 2),
                      )
                    : Text(ingredient == null ? "Сохранить" : "Обновить"),
              ),
            ],
          );
        },
      ),
    );
  }

  void _showStockOperationDialog(Ingredient ingredient, String type) {
    // type: 'add' or 'remove'
    final quantityController = TextEditingController();
    final noteController = TextEditingController();
    bool isLoading = false;

    showDialog(
      context: context,
      builder: (context) => StatefulBuilder(
        builder: (context, setState) {
          return AlertDialog(
            title: Text(type == 'add' ? "Приход товара" : "Списание товара"),
            content: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                Text("Ингредиент: ${ingredient.name}"),
                const SizedBox(height: 10),
                TextField(
                  controller: quantityController,
                  keyboardType: TextInputType.number,
                  decoration: InputDecoration(
                    labelText:
                        "${AppLocalizations.of(context)!.quantityLabel} (${ingredient.unit})",
                    border: const OutlineInputBorder(),
                  ),
                ),
                const SizedBox(height: 10),
                TextField(
                  controller: noteController,
                  decoration: InputDecoration(
                    labelText: AppLocalizations.of(context)!.noteLabel,
                    border: const OutlineInputBorder(),
                  ),
                ),
              ],
            ),
            actions: [
              TextButton(
                onPressed: isLoading ? null : () => Navigator.pop(context),
                child: Text(AppLocalizations.of(context)!.cancel),
              ),
              ElevatedButton(
                style: ElevatedButton.styleFrom(
                  backgroundColor: type == 'add' ? Colors.green : Colors.red,
                  foregroundColor: Colors.white,
                ),
                onPressed: isLoading
                    ? null
                    : () async {
                        final qty = double.tryParse(quantityController.text);
                        if (qty == null || qty <= 0) return;

                        setState(() => isLoading = true);
                        try {
                          if (type == 'add') {
                            await _warehouseService.addStock(
                              ingredientId: ingredient.id,
                              quantityToAdd: qty,
                              userId: 'admin', // Replace with real ID if needed
                              note: noteController.text,
                              cost: 0,
                            );
                          } else {
                            await _warehouseService.removeStock(
                              ingredientId: ingredient.id,
                              quantityToRemove: qty,
                              userId: 'admin',
                              type: 'manual_writeoff',
                              note: noteController.text,
                            );
                          }
                          if (context.mounted) Navigator.pop(context);
                        } catch (e) {
                          if (context.mounted) {
                            setState(() => isLoading = false);
                            ScaffoldMessenger.of(context).showSnackBar(
                              SnackBar(content: Text("Ошибка: $e")),
                            );
                          }
                        }
                      },
                child: isLoading
                    ? const SizedBox(
                        width: 20,
                        height: 20,
                        child: CircularProgressIndicator(
                          strokeWidth: 2,
                          color: Colors.white,
                        ),
                      )
                    : Text(
                        type == 'add'
                            ? AppLocalizations.of(context)!.add
                            : AppLocalizations.of(context)!.writeOff,
                      ),
              ),
            ],
          );
        },
      ),
    );
  }

  // --- UI ---

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    return Scaffold(
      backgroundColor: theme.scaffoldBackgroundColor,
      appBar: AppBar(
        title: Text(
          AppLocalizations.of(context)!.warehouseTitle,
          style: theme.textTheme.titleLarge,
        ),
        backgroundColor: theme.appBarTheme.backgroundColor,
        elevation: 0,
        bottom: TabBar(
          controller: _tabController,
          labelColor: AppColors.primary,
          unselectedLabelColor: Colors.grey,
          indicatorColor: AppColors.primary,
          tabs: [
            Tab(text: AppLocalizations.of(context)!.inventory),
            Tab(text: AppLocalizations.of(context)!.history),
          ],
        ),
        actions: [
          IconButton(
            onPressed: () => _showAddEditIngredientDialog(),
            icon: const Icon(Icons.add),
            tooltip: AppLocalizations.of(context)!.addIngredient,
          ),
        ],
      ),
      body: TabBarView(
        controller: _tabController,
        children: [
          // Tab 1: Inventory List
          Column(
            children: [
              Padding(
                padding: const EdgeInsets.all(16.0),
                child: TextField(
                  decoration: InputDecoration(
                    hintText: AppLocalizations.of(context)!.searchIngredients,
                    prefixIcon: const Icon(Icons.search),
                    filled: true,
                    fillColor: theme.brightness == Brightness.dark
                        ? theme.colorScheme.surfaceContainerHighest
                        : Colors.white,
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(12),
                      borderSide: BorderSide.none,
                    ),
                  ),
                  onChanged: (val) =>
                      setState(() => _searchQuery = val.toLowerCase()),
                ),
              ),
              Expanded(
                child: StreamBuilder<List<Ingredient>>(
                  stream: _warehouseService.getIngredients(),
                  builder: (context, snapshot) {
                    if (snapshot.connectionState == ConnectionState.waiting) {
                      return const Center(child: CircularProgressIndicator());
                    }
                    if (snapshot.hasError) {
                      return Center(child: Text("Ошибка: ${snapshot.error}"));
                    }

                    final allItems = snapshot.data ?? [];
                    final items = allItems.where((item) {
                      return item.name.toLowerCase().contains(_searchQuery);
                    }).toList();

                    if (items.isEmpty) {
                      return Center(
                        child: Text(
                          AppLocalizations.of(context)!.noIngredientsFound,
                          style: TextStyle(color: Colors.grey[500]),
                        ),
                      );
                    }

                    return ListView.builder(
                      padding: const EdgeInsets.only(
                        left: 16,
                        right: 16,
                        bottom: 80,
                      ),
                      itemCount: items.length,
                      itemBuilder: (context, index) {
                        final ingredient = items[index];
                        return Card(
                          margin: const EdgeInsets.only(bottom: 12),
                          shape: RoundedRectangleBorder(
                            borderRadius: BorderRadius.circular(12),
                          ),
                          child: InkWell(
                            onTap: () =>
                                _showStockOperationDialog(ingredient, 'add'),
                            onLongPress: () => _showAddEditIngredientDialog(
                              ingredient: ingredient,
                            ),
                            borderRadius: BorderRadius.circular(12),
                            child: Padding(
                              padding: const EdgeInsets.all(16),
                              child: Row(
                                children: [
                                  CircleAvatar(
                                    backgroundColor: ingredient.isLowStock
                                        ? Colors.red.withOpacity(0.1)
                                        : Colors.green.withOpacity(0.1),
                                    child: Icon(
                                      Icons.kitchen,
                                      color: ingredient.isLowStock
                                          ? Colors.red
                                          : Colors.green,
                                    ),
                                  ),
                                  const SizedBox(width: 16),
                                  Expanded(
                                    child: Column(
                                      crossAxisAlignment:
                                          CrossAxisAlignment.start,
                                      children: [
                                        Text(
                                          ingredient.name,
                                          style: const TextStyle(
                                            fontWeight: FontWeight.bold,
                                            fontSize: 16,
                                          ),
                                        ),
                                        Text(
                                          "${ingredient.quantity.toStringAsFixed(1)} ${ingredient.unit}",
                                          style: TextStyle(
                                            color: ingredient.isLowStock
                                                ? Colors.red
                                                : theme
                                                      .textTheme
                                                      .bodyMedium
                                                      ?.color
                                                      ?.withOpacity(0.8),
                                            fontWeight: FontWeight.bold,
                                          ),
                                        ),
                                        if (ingredient.isLowStock)
                                          Text(
                                            "Мин: ${ingredient.minQuantity}",
                                            style: const TextStyle(
                                              color: Colors.red,
                                              fontSize: 12,
                                            ),
                                          ),
                                      ],
                                    ),
                                  ),
                                  IconButton(
                                    icon: const Icon(
                                      Icons.remove_circle_outline,
                                      color: Colors.red,
                                    ),
                                    onPressed: () => _showStockOperationDialog(
                                      ingredient,
                                      'remove',
                                    ),
                                  ),
                                  IconButton(
                                    icon: const Icon(
                                      Icons.add_circle_outline,
                                      color: AppColors.primary,
                                    ),
                                    onPressed: () => _showStockOperationDialog(
                                      ingredient,
                                      'add',
                                    ),
                                  ),
                                ],
                              ),
                            ),
                          ),
                        );
                      },
                    );
                  },
                ),
              ),
            ],
          ),

          // Tab 2: History
          const WarehouseTransactionsScreen(),
        ],
      ),
    );
  }
}
